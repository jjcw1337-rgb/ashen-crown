"""Writes the joint layout exported by rig_meshy_knight.py into scripts/knight.gd (MESHY_LAYOUT and
MESHY_BONES, between the "# meshy layout begin/end" markers). python3 layout_to_gd.py layout.json [armored]
With "armored" (rig_armored_knight.py) it writes ARMORED_LAYOUT/ARMORED_BONES between "# armored layout" markers."""
import json, sys, re, os
d = json.load(open(sys.argv[1]))
kind = sys.argv[2] if len(sys.argv) > 2 else "meshy"
NAME = kind.upper()
L, P = d["layout"], d["parents"]
order = []
def visit(n):
    if n in order:
        return
    if P.get(n):
        visit(P[n])
    order.append(n)
for n in L:
    visit(n)
f = lambda v: repr(round(float(v), 4) + 0.0)
lines = [f"# {kind} layout begin (generated by tools/blender/knight/layout_to_gd.py)", f"const {NAME}_LAYOUT := {{"]
for n in order:
    v = L[n]
    lines.append(f'\t"{n}": ["{P.get(n) or ""}", Vector3({f(v[0])}, {f(v[1])}, {f(v[2])})],')
lines += ["}", f"const {NAME}_BONES := [" + ", ".join(f'"{n}"' for n in order) + "]", f"# {kind} layout end"]
path = os.path.join(os.path.dirname(__file__), "../../../scripts/knight.gd")
src = open(path).read()
new = re.sub(rf"# {kind} layout begin.*?# {kind} layout end", lambda m: "\n".join(lines), src, flags=re.S)
assert f"# {kind} layout begin" in src, "markers missing"
open(path, "w").write(new)
print("wrote", len(order), "bones")
