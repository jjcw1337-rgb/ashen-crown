"""Writes the joint layout exported by rig_meshy_knight.py into scripts/knight.gd (MESHY_LAYOUT and
MESHY_BONES, between the "# meshy layout begin/end" markers). python3 layout_to_gd.py layout.json"""
import json, sys, re, os
d = json.load(open(sys.argv[1]))
L, P = d["layout"], d["parents"]
order = []
def visit(n):
    if n in order:
        return
    if P.get(n):
        visit(P[n])
    order.append(n)
for n in L:
    visit(n)
f = lambda v: repr(round(float(v), 4) + 0.0)
lines = ["# meshy layout begin (generated by tools/blender/knight/layout_to_gd.py)", "const MESHY_LAYOUT := {"]
for n in order:
    v = L[n]
    lines.append(f'\t"{n}": ["{P.get(n) or ""}", Vector3({f(v[0])}, {f(v[1])}, {f(v[2])})],')
lines += ["}", "const MESHY_BONES := [" + ", ".join(f'"{n}"' for n in order) + "]", "# meshy layout end"]
path = os.path.join(os.path.dirname(__file__), "../../../scripts/knight.gd")
src = open(path).read()
new = re.sub(r"# meshy layout begin.*?# meshy layout end", "\n".join(lines), src, flags=re.S)
assert new != src or "# meshy layout begin" in src, "markers missing"
open(path, "w").write(new)
print("wrote", len(order), "bones")
